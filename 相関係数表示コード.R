# ---------------------------------------------------------
# 相関の強い順にペアを表示するコード
# ---------------------------------------------------------

# 相関係数行列をロング形式に変換
cor_list_display <- cor_matrix_initial %>%
  as_tibble(rownames = "変数1") %>%
  pivot_longer(cols = -変数1, names_to = "変数2", values_to = "相関係数r") %>%
  # 同じ変数同士の組み合わせを除外
  filter(変数1 != 変数2) %>%
  # 絶対値で評価（正の相関も負の相関も「似ている」ため）
  mutate(abs_r = abs(相関係数r)) %>%
  # 重複（A-B と B-A）を排除
  filter(変数1 < 変数2) %>%
  # 相関が強い順に並び替え
  arrange(desc(abs_r))

# 結果の表示（上位20ペアを表示）
cat("\n--- 相関の強い変数ペア（TOP 20） ---\n")
print(head(cor_list_display, 20))

